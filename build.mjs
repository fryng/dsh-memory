#!/usr/bin/env node
/**
 * esbuild, two bundles:
 *   src/index.js        -> lib/index.js         (ESM, node platform, Host half)
 *   src/client/index.js -> lib/client.js        (CJS-in-a-wrapper, browser half)
 *
 * Zero runtime dependencies on either side: Host services arrive through the
 * cordis context, and the browser half only `require`s the shell's seed modules
 * (react + primitives), which are external here by design.
 *
 * The browser bundle is NOT plain ESM: `dsh-client-modules` boots client
 * bundles by calling `window.__ModuleLoader__.load({ id, factory })`, so the
 * CommonJS output esbuild produces is wrapped in that factory by the banner and
 * footer below. Emitting ESM there would load nothing and log nothing.
 */
import { build } from 'esbuild';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(fileURLToPath(import.meta.url));
const watch = process.argv.includes('--watch');
const pkg = 'dsh-memory';

/** Modules the web shell provides; bundling them would duplicate React. */
const CLIENT_EXTERNAL = [
  'react',
  'react/jsx-runtime',
  'react-dom',
  'react-dom/client',
  '@deepseek-ai/cordis',
  '@deepseek-ai/dsh-client-store',
  '@deepseek-ai/dsh-client-ui-slots',
  '@deepseek-ai/dsh-client-ui-primitives',
];

/** @type {import('esbuild').BuildOptions} */
const hostOptions = {
  entryPoints: [path.join(root, 'src/index.js')],
  outfile: path.join(root, 'lib/index.js'),
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node22',
  sourcemap: true,
  legalComments: 'none',
  logLevel: 'info',
  banner: {
    js: `// ${pkg} — generated by build.mjs, do not edit by hand.`,
  },
};

/** @type {import('esbuild').BuildOptions} */
const clientOptions = {
  entryPoints: [path.join(root, 'src/client/index.js')],
  outfile: path.join(root, 'lib/client.js'),
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  sourcemap: true,
  legalComments: 'none',
  logLevel: 'info',
  jsx: 'automatic',
  loader: { '.js': 'jsx' },
  external: CLIENT_EXTERNAL,
  banner: {
    js: [
      `// ${pkg} — browser half, generated by build.mjs, do not edit by hand.`,
      'window.__ModuleLoader__.load({',
      `\tid: ${JSON.stringify(pkg)},`,
      '\tfactory: (require) => {',
      '\t\tvar module = { exports: {} };',
      '\t\tvar exports = module.exports;',
    ].join('\n'),
  },
  footer: {
    js: '\n\t\treturn module.exports;\n\t}\n});',
  },
};

const targets = [hostOptions, clientOptions];

if (watch) {
  const { context } = await import('esbuild');
  for (const options of targets) {
    const ctx = await context(options);
    await ctx.watch();
  }
  console.log(`[${pkg}] watching src/…`);
} else {
  for (const options of targets) {
    await build(options);
  }
}
